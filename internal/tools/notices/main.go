// notices writes THIRD_PARTY_NOTICES.md: the license of every module linked
// into the ntbrowser binary, read from the module cache, so that what the
// binary carries is what it credits.
//
//	go run ./internal/tools/notices > THIRD_PARTY_NOTICES.md
//	go run ./internal/tools/notices -media > cmd/ntbrowser-media/THIRD_PARTY_NOTICES.md
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type module struct {
	path, version, dir, replaces string
}

var licenseName = regexp.MustCompile(`(?i)^(LICENSE|LICENCE|COPYING|NOTICE)(\.(txt|md|rst))?$`)

// Licenses of embedded assets that live outside a module's root license
// files. Every pattern must match, so an upstream move fails here instead of
// silently dropping a notice.
var assets = map[string][]string{
	"golang.org/x/image":             {"font/gofont/ttfs/README"}, // Go fonts, nthtml's last fallback
	"nimbleterminal.dev/ntfonts":     {"*.OFL.txt"},
	"nimbleterminal.dev/ntfonts/cjk": {"internal/notice/*.OFL.txt"},
}

// Notes printed under a module's heading.
var notes = map[string]string{
	"golang.org/x/net":               "Also covers the SVG name tables copied into `dom/svgcase.go`.",
	"nimbleterminal.dev/ntfonts":     "The embedded font subsets are SIL OFL-1.1, renamed internally to Gloss Text; the module source is MIT.",
	"nimbleterminal.dev/ntfonts/cjk": "Linked unless built with `-tags nocjk`. The embedded Noto Sans CJK SC subset is SIL OFL-1.1, renamed internally to Gloss Text CJKSC.",
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	media := len(os.Args) > 1 && os.Args[1] == "-media"
	// The default build is a superset of -tags nocjk.
	cmd := exec.Command("go", "list", "-deps", "-f", `{{with .Module}}{{.Path}}	{{if .Replace}}{{with .Replace}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{else}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{end}}`, "./cmd/ntbrowser")
	binary := "ntbrowser"
	if media {
		cmd.Args[len(cmd.Args)-1] = "."
		cmd.Dir = "cmd/ntbrowser-media"
		binary = "ntbrowser-media"
	}
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("go list: %w", err)
	}
	modules := map[string]module{}
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		fields := strings.Split(line, "\t")
		if len(fields) != 4 || fields[3] == "" || strings.HasPrefix(fields[0], "nimbleterminal.dev/ntbrowser") {
			continue
		}
		m := module{path: fields[1], version: fields[2], dir: fields[3]}
		if fields[0] != fields[1] {
			m.replaces = fields[0]
		}
		if m.version == "" { // a local replace
			m.path, m.version, m.replaces = fields[0], "(local)", ""
		}
		modules[m.path] = m
	}
	var paths []string
	for p := range modules {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString(`# Third-party notices

ntbrowser is MIT licensed; see LICENSE. The ` + binary + ` binary links the
dependencies below. Generated by internal/tools/notices (` + "`task notices`" + `).

`)
	// The Go runtime and standard library are compiled into every binary.
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return err
	}
	text, err := goLicense(strings.TrimSpace(string(goroot)))
	if err != nil {
		return err
	}
	section(&b, "The Go runtime and standard library", "https://go.dev", text)
	var missing []string
	for _, p := range paths {
		m := modules[p]
		texts, err := licenseTexts(m)
		if err != nil {
			return err
		}
		if len(texts) == 0 {
			missing = append(missing, p)
			continue
		}
		title := m.path + " " + m.version
		if m.replaces != "" {
			title += " (replaces " + m.replaces + ")"
		}
		section(&b, title, notes[m.path], bytes.Join(texts, []byte("\n\n")))
	}
	if len(missing) > 0 {
		return fmt.Errorf("no license file in: %s", strings.Join(missing, ", "))
	}
	for p := range assets {
		if _, ok := modules[p]; !ok && !media {
			return fmt.Errorf("asset licenses listed for %s, which is not linked", p)
		}
	}
	_, err = os.Stdout.Write(append(bytes.TrimRight(b.Bytes(), "\n"), '\n'))
	return err
}

// licenseTexts returns the module's root license files, then its asset
// licenses, each asset text headed by its path in the module.
func licenseTexts(m module) ([][]byte, error) {
	entries, err := os.ReadDir(m.dir)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", m.path, err)
	}
	var texts [][]byte
	for _, e := range entries {
		if !e.IsDir() && licenseName.MatchString(e.Name()) {
			text, err := os.ReadFile(filepath.Join(m.dir, e.Name()))
			if err != nil {
				return nil, err
			}
			texts = append(texts, text)
		}
	}
	for _, pattern := range assets[m.path] {
		names, err := filepath.Glob(filepath.Join(m.dir, pattern))
		if err != nil {
			return nil, err
		}
		if len(names) == 0 {
			return nil, fmt.Errorf("%s: no asset license matches %s", m.path, pattern)
		}
		sort.Strings(names)
		for _, name := range names {
			text, err := os.ReadFile(name)
			if err != nil {
				return nil, err
			}
			rel, _ := filepath.Rel(m.dir, name)
			texts = append(texts, append([]byte("--- "+filepath.ToSlash(rel)+" ---\n\n"), text...))
		}
	}
	return texts, nil
}

// Homebrew keeps Go in libexec and its license in the enclosing keg.
func goLicense(root string) ([]byte, error) {
	root = filepath.Clean(root)
	name := filepath.Join(root, "LICENSE")
	text, err := os.ReadFile(name)
	if os.IsNotExist(err) && filepath.Base(root) == "libexec" {
		parent := filepath.Join(filepath.Dir(root), "LICENSE")
		text, err = os.ReadFile(parent)
		if err != nil {
			return nil, fmt.Errorf("runtime license for Go (checked %s and %s): %w", name, parent, err)
		}
	}
	if err != nil {
		return nil, fmt.Errorf("runtime license for Go %s: %w", name, err)
	}
	return text, nil
}

func section(b *bytes.Buffer, title, note string, text []byte) {
	fmt.Fprintf(b, "## %s\n\n", title)
	if note != "" {
		fmt.Fprintf(b, "%s\n\n", note)
	}
	b.WriteString("```\n")
	b.Write(bytes.TrimRight(text, "\n"))
	b.WriteString("\n```\n\n")
}
